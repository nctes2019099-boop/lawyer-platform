// Minimal offline SQLite schema bootstrap using @libsql/client (pure JS/WASM).
// Used when the native Prisma schema engine cannot run (offline/restricted).
// Mirrors prisma/schema.prisma. For normal dev, prefer `prisma db push`.
import { createClient } from "@libsql/client";

const db = createClient({ url: "file:prisma/dev.db" });

const SQL = `
CREATE TABLE IF NOT EXISTS User (
  id TEXT PRIMARY KEY, email TEXT NOT NULL UNIQUE, password TEXT NOT NULL,
  name TEXT, phone TEXT, governorate TEXT, barMember TEXT, avatar TEXT,
  role TEXT NOT NULL DEFAULT 'lawyer', isAdmin INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS PasswordResetToken (
  id TEXT PRIMARY KEY, token TEXT NOT NULL UNIQUE, userId TEXT NOT NULL,
  expiresAt DATETIME NOT NULL, used INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Client (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT, phone TEXT, address TEXT,
  governorate TEXT, category TEXT NOT NULL DEFAULT 'عامة', notes TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS "Case" (
  id TEXT PRIMARY KEY, caseNumber TEXT NOT NULL, title TEXT NOT NULL, description TEXT,
  type TEXT NOT NULL DEFAULT 'مدني', status TEXT NOT NULL DEFAULT 'قيد النظر',
  priority TEXT NOT NULL DEFAULT 'عادية', court TEXT, judge TEXT, clientId TEXT,
  ownerId TEXT NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (clientId) REFERENCES Client(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Session (
  id TEXT PRIMARY KEY, date DATETIME NOT NULL, location TEXT, status TEXT NOT NULL DEFAULT 'قادمة',
  notes TEXT, caseId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Appointment (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, date DATETIME NOT NULL, location TEXT,
  type TEXT NOT NULL DEFAULT 'جلسة', status TEXT NOT NULL DEFAULT 'قادمة', notes TEXT,
  caseId TEXT, clientId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (clientId) REFERENCES Client(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS Appointment_caseId_idx ON Appointment(caseId);
CREATE TABLE IF NOT EXISTS Note (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, content TEXT, category TEXT NOT NULL DEFAULT 'شخصي',
  pinned INTEGER NOT NULL DEFAULT 0, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Law (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, number TEXT, year TEXT,
  category TEXT NOT NULL DEFAULT 'مدني', content TEXT NOT NULL,
  isFavorite INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS Petition (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, content TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'عريضة', status TEXT NOT NULL DEFAULT 'قيد التنفيذ',
  caseId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Document (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, type TEXT NOT NULL DEFAULT 'وثيقة',
  fileUrl TEXT, fileSize TEXT, fileExt TEXT, caseId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS DocumentAccess (
  id TEXT PRIMARY KEY, token TEXT NOT NULL UNIQUE, documentId TEXT NOT NULL,
  expiresAt DATETIME NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS DocumentAccess_documentId_idx ON DocumentAccess(documentId);
CREATE TABLE IF NOT EXISTS Activity (
  id TEXT PRIMARY KEY, type TEXT NOT NULL, title TEXT NOT NULL, description TEXT,
  caseId TEXT, clientId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS Notification (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, message TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'info', read INTEGER NOT NULL DEFAULT 0,
  ownerId TEXT NOT NULL, createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS AuditLog (
  id TEXT PRIMARY KEY, action TEXT NOT NULL, entity TEXT NOT NULL,
  entityId TEXT, details TEXT, userId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS SubscriptionPlan (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, description TEXT, price REAL NOT NULL,
  currency TEXT NOT NULL DEFAULT 'IQD', durationDays INTEGER NOT NULL,
  features TEXT, limits TEXT, isActive INTEGER NOT NULL DEFAULT 1,
  sortOrder INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS Subscription (
  id TEXT PRIMARY KEY, userId TEXT NOT NULL UNIQUE, planId TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'PENDING', startDate DATETIME, endDate DATETIME,
  autoRenew INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (planId) REFERENCES SubscriptionPlan(id)
);
CREATE TABLE IF NOT EXISTS Payment (
  id TEXT PRIMARY KEY, userId TEXT NOT NULL, planId TEXT, provider TEXT NOT NULL DEFAULT 'mock',
  paymentMethod TEXT NOT NULL DEFAULT 'card', amount REAL NOT NULL, currency TEXT NOT NULL DEFAULT 'IQD',
  status TEXT NOT NULL DEFAULT 'PENDING', transactionId TEXT NOT NULL UNIQUE,
  providerPaymentId TEXT, metadata TEXT, paidAt DATETIME,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (userId) REFERENCES User(id) ON DELETE CASCADE,
  FOREIGN KEY (planId) REFERENCES SubscriptionPlan(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS PaymentWebhookEvent (
  id TEXT PRIMARY KEY, provider TEXT NOT NULL, eventId TEXT NOT NULL UNIQUE,
  eventType TEXT NOT NULL, payload TEXT NOT NULL, processed INTEGER NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS "Transaction" (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, description TEXT, amount REAL NOT NULL,
  type TEXT NOT NULL DEFAULT 'expense', category TEXT NOT NULL DEFAULT 'مصاريف محكمة',
  caseId TEXT, clientId TEXT, ownerId TEXT NOT NULL,
  date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (clientId) REFERENCES Client(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS Transaction_ownerId_idx ON "Transaction"(ownerId);
CREATE INDEX IF NOT EXISTS Transaction_type_idx ON "Transaction"(type);
CREATE INDEX IF NOT EXISTS Transaction_date_idx ON "Transaction"(date);
CREATE TABLE IF NOT EXISTS Task (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, description TEXT, status TEXT NOT NULL DEFAULT 'pending',
  priority TEXT NOT NULL DEFAULT 'عادية', dueDate DATETIME, completedAt DATETIME,
  caseId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS Task_ownerId_idx ON Task(ownerId);
CREATE INDEX IF NOT EXISTS Task_status_idx ON Task(status);
CREATE INDEX IF NOT EXISTS Task_caseId_idx ON Task(caseId);
CREATE TABLE IF NOT EXISTS TimeEntry (
  id TEXT PRIMARY KEY, description TEXT, startTime DATETIME NOT NULL, endTime DATETIME,
  duration INTEGER NOT NULL DEFAULT 0, billable INTEGER NOT NULL DEFAULT 1,
  hourlyRate REAL NOT NULL DEFAULT 0, caseId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (caseId) REFERENCES "Case"(id) ON DELETE SET NULL,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS TimeEntry_ownerId_idx ON TimeEntry(ownerId);
CREATE INDEX IF NOT EXISTS TimeEntry_caseId_idx ON TimeEntry(caseId);
CREATE INDEX IF NOT EXISTS TimeEntry_startTime_idx ON TimeEntry(startTime);
CREATE TABLE IF NOT EXISTS Reminder (
  id TEXT PRIMARY KEY, title TEXT NOT NULL, description TEXT, dueAt DATETIME NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', type TEXT NOT NULL DEFAULT 'general',
  caseId TEXT, ownerId TEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (ownerId) REFERENCES User(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS Reminder_ownerId_idx ON Reminder(ownerId);
CREATE INDEX IF NOT EXISTS Reminder_dueAt_idx ON Reminder(dueAt);
CREATE INDEX IF NOT EXISTS Reminder_status_idx ON Reminder(status);
`;

// SQLite executes one statement per execute() in libsql; split safely.
for (const stmt of SQL.split(/;\s*\n/).map((s) => s.trim()).filter(Boolean)) {
  await db.execute(stmt);
}
console.log("SQLite schema initialized via libsql.");
